package dev.origamiguide.api.catalog;

/** Kind of paper recommended for a model. */
public enum PaperType {
    /** Thin origami paper, colored on one side. The default choice. */
    KAMI,
    /** Regular printer paper cut to a square. */
    PRINTER,
    /** Foil-backed paper that holds shapes well. */
    FOIL,
    /** Soft, strong Japanese paper. */
    WASHI
}
